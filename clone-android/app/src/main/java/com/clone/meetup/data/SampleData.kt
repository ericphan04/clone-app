package com.clone.meetup.data

/** Mirrors com.meetup.feature.event.model / group model shapes as seen in the nav-graph args. */
data class Event(
    val id: String,
    val title: String,
    val groupName: String,
    val groupUrlname: String,
    val startEpochMillis: Long,
    val endEpochMillis: Long,
    val timezone: String,
    val venueName: String,
    val venueCity: String,
    val category: String,
    val imageUrl: String,
    val attendeeCount: Int,
    val attendeeAvatars: List<String>,
    val isOnline: Boolean = false,
    val isFeatured: Boolean = false,
    val isLive: Boolean = false,
    val hasFee: Boolean = false,
    val description: String = "",
    val host: String = "",
)

data class Group(
    val id: String,
    val name: String,
    val urlname: String,
    val memberCount: Int,
    val coverUrl: String,
    val topics: List<String>,
    val city: String,
    val isPrivate: Boolean = false,
    val nextEventTitle: String? = null,
)

data class Category(
    val id: String,
    val label: String,
    val emoji: String,
)

data class MessageThread(
    val id: String,
    val title: String,
    val preview: String,
    val timestamp: String,
    val avatarUrl: String,
    val unread: Boolean,
    val isGroupChat: Boolean,
)

data class Notification(
    val id: String,
    val title: String,
    val body: String,
    val timestamp: String,
    val avatarUrl: String,
    val isUnread: Boolean,
)

